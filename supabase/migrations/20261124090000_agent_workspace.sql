create table if not exists public.user_profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'student' check (role in ('student', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  seed_key text,
  title text not null check (char_length(title) between 1 and 200),
  course text not null default 'Personnel' check (char_length(course) <= 120),
  due text not null default 'À planifier' check (char_length(due) <= 120),
  priority text not null default 'Normal'
    check (priority in ('Urgent', 'Normal', 'Faible')),
  done boolean not null default false,
  instructions text check (char_length(instructions) <= 2000),
  estimated_time text check (char_length(estimated_time) <= 100),
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, seed_key)
);

create table if not exists public.schedule_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  seed_key text,
  event_id bigint,
  title text not null check (char_length(title) between 1 and 200),
  item_type text not null check (item_type in ('cours', 'association', 'personnel')),
  organizer text not null default '',
  start_time text not null default '',
  end_time text not null default '',
  event_date text not null default '',
  full_date text not null default '',
  place text not null default '',
  detail text not null default '',
  badge text not null default '',
  color text not null default '',
  light text not null default '',
  text_color text not null default '',
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, seed_key),
  unique (id, user_id)
);

create table if not exists public.association_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  seed_key text,
  email_id bigint not null default 0,
  title text not null check (char_length(title) between 1 and 200),
  association text not null default '',
  event_date text not null default '',
  full_date text not null default '',
  day text not null default '',
  month text not null default '',
  event_time text not null default '',
  place text not null default '',
  category text not null default 'Vie étudiante'
    check (category in ('Soirée', 'Sport', 'Culture', 'Solidarité', 'Conférence', 'Vie étudiante')),
  badge text not null default '',
  source_subject text not null default '',
  description text not null default '',
  color text not null default '',
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, seed_key),
  unique (id, user_id)
);

alter table public.schedule_items
  add constraint schedule_items_event_owner_fk
  foreign key (event_id, user_id)
  references public.association_events (id, user_id)
  on delete set null (event_id);

create table if not exists public.email_categories (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  parent_id bigint,
  name text not null check (char_length(name) between 1 and 80),
  created_at timestamptz not null default now(),
  unique (id, user_id),
  foreign key (parent_id, user_id)
    references public.email_categories (id, user_id)
    on delete cascade
);

create table if not exists public.email_annotations (
  user_id uuid not null references auth.users (id) on delete cascade,
  message_uid bigint not null check (message_uid > 0),
  category_id bigint,
  priority text not null default 'Normal'
    check (priority in ('Urgent', 'Normal', 'Faible')),
  labels text[] not null default '{}',
  updated_at timestamptz not null default now(),
  primary key (user_id, message_uid),
  foreign key (category_id, user_id)
    references public.email_categories (id, user_id)
    on delete set null (category_id)
);

create table if not exists public.agent_action_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  module text not null,
  action text not null,
  target_id text,
  result text not null check (result in ('success', 'failure')),
  created_at timestamptz not null default now()
);

