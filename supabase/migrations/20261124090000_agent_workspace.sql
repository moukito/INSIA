create or replace function public.audit_agent_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  changed_row jsonb;
  target text;
begin
  if tg_op = 'DELETE' then
    changed_row := to_jsonb(old);
  else
    changed_row := to_jsonb(new);
  end if;

  if auth.uid() is not null then
    target := coalesce(changed_row ->> 'id', changed_row ->> 'message_uid');
    insert into public.agent_action_log (user_id, module, action, target_id, result)
    values (auth.uid(), tg_table_name, lower(tg_op), target, 'success');
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

create trigger audit_tasks
  after insert or update or delete on public.tasks
  for each row execute procedure public.audit_agent_change();
create trigger audit_schedule_items
